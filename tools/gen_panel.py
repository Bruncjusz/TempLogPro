"""Generate Src/templogpro_panel_html.inc from panel/templogpro.html.


Template rules (so the source can be readable while the image stays compact):

- Line breaks and leading indentation are dropped; write an explicit space

  where one is needed, and end every JS statement with a semicolon.

- Lines starting with "##" are comments and are dropped.

- {{NL}} becomes a real newline.

- {{FW_VERSION}}, {{PRODUCT}} and {{AUTHOR}} come from Inc/templogpro_version.h.

- {{DEVICE_DATA}} marks where the firmware inserts DATA.CSV and the config

  JSON block (see html_copy() in Src/templogpro_usb_files.c).


Usage:

  python tools/gen_panel.py           write the .inc and tmp/panel_preview.html

  python tools/gen_panel.py --check   exit 1 if the .inc is out of date

"""

import json

import re

import sys

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]

TEMPLATE = ROOT / 'panel' / 'templogpro.html'

OUTPUT = ROOT / 'Src' / 'templogpro_panel_html.inc'

PREVIEW = ROOT / 'tmp' / 'panel_preview.html'

MARKER = '{{DEVICE_DATA}}'

VERSION_H = ROOT / 'Inc' / 'templogpro_version.h'

C_LINE = 120


def _preview_csv():
    """Sample log across the 2026-10-25 switch to winter time in Europe/Warsaw
    (01:00 UTC): local 02:00-02:59 appears twice, with +02:00 then +01:00."""
    import datetime
    t0 = datetime.datetime(2026, 10, 24, 23, 0, 0)
    switch = datetime.datetime(2026, 10, 25, 1, 0, 0)
    head = 'Sequence,Date,Time,Temperature_C,Code,UTC_Offset\r\n'

    def line(seq, utc, temp, code):
        off = 120 if utc < switch else 60
        local = utc + datetime.timedelta(minutes=off)
        return f'{seq:05d},{local:%Y-%m-%d},{local:%H:%M:%S},{temp:+08.3f},{code},+{off // 60:02d}:00\r\n'
    rows = [line(1, t0, 0, 'R001')]
    for i in range(240):
        v = 24 + (i % 40) / 8
        rows.append(line(i + 2, t0 + datetime.timedelta(seconds=60 * i), v, 'T001' if (i % 40) > 30 else 'M000'))
    rows.append('00242,1970-01-01,00:00:00,+000.000,E001,+00:00\r\n')
    rows.append(line(243, t0 + datetime.timedelta(seconds=60 * 240), 0, 'R002'))
    return head + ''.join(rows)


PREVIEW_CSV = _preview_csv()

PREVIEW_CONFIG = {'interval': 60, 'low': 24, 'high': 27.5, 'battery': 1, 'usbLogging': 1, 'lcd': 0,

                  'lcdMenu': 131071, 'records': 243, 'capacity': 42284, 'pdf': 1, 'led': 1, 'unit': 0, 'reset': 'POWER_ON', 'clockMode': 0, 'ecoMode': 0, 'alarmDelay': 0, 'lcdOrder': [12, 15, 16, 1, 4, 3, 6, 2, 5, 7, 8, 9, 10, 11], 'vbatMin': 2930,

                  'tzName': 'Europe/Warsaw', 'tzStd': 60, 'tzDst': 60, 'tzStart': [3, 5, 0, 120], 'tzEnd': [10, 5, 0, 180]}


def render(template_text):

    parts = []

    for line in template_text.splitlines():

        stripped = line.lstrip(' \t')

        if stripped.startswith('##'):

            continue

        parts.append(stripped)

    header = VERSION_H.read_text(encoding='utf-8')

    define = lambda name: re.search(r'#define\s+' + name + r'\s+"([^"]+)"', header).group(1)

    text = (''.join(parts).replace('{{NL}}', '\n').replace('{{FW_VERSION}}', define('TEMPLOGPRO_FW_VERSION'))

            .replace('{{PRODUCT}}', define('TEMPLOGPRO_PRODUCT_NAME')).replace('{{AUTHOR}}', define('TEMPLOGPRO_AUTHOR')))

    if text.count(MARKER) != 1:

        raise SystemExit(f'{TEMPLATE}: expected exactly one {MARKER}')

    return text.split(MARKER)


def c_literal_lines(text):

    out = []

    current = ''

    for ch in text:

        code = ord(ch)

        if ch == '\\':

            piece = '\\\\'

        elif ch == '"':

            piece = '\\"'

        elif ch == '\n':

            piece = '\\n'

        elif code < 32 or code == 127:

            piece = f'\\{code:03o}'

        else:

            piece = ch  # UTF-8 is GCC's default source and execution charset

        if len(current) + len(piece) > C_LINE:

            out.append(f'"{current}"')

            current = ''

        current += piece

    if current:

        out.append(f'"{current}"')

    return out


def generate():

    prefix, suffix = render(TEMPLATE.read_text(encoding='utf-8'))

    lines = ['/* Generated by tools/gen_panel.py from panel/templogpro.html. Do not edit. */',

             'static const char HTML_PREFIX[] =']

    lines += c_literal_lines(prefix)

    lines += [';', '', 'static const char HTML_SUFFIX[] =']

    lines += c_literal_lines(suffix)

    lines += [';', '']

    return '\n'.join(lines), prefix, suffix


def main():

    code, prefix, suffix = generate()

    if '--check' in sys.argv:

        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''

        if current != code:

            print(f'{OUTPUT.relative_to(ROOT)} is out of date: run python tools/gen_panel.py')

            sys.exit(1)

        print('panel .inc is up to date')

        return

    OUTPUT.write_text(code, encoding='utf-8', newline='\n')

    PREVIEW.parent.mkdir(exist_ok=True)

    config_block = ('</script><script id="config-data" type="application/json">'

                    + json.dumps(PREVIEW_CONFIG, separators=(',', ':')) + '</script><script>')

    PREVIEW.write_text(prefix + PREVIEW_CSV + config_block + suffix, encoding='utf-8', newline='')

    size = len(prefix.encode('utf-8')) + len(suffix.encode('utf-8'))

    print(f'wrote {OUTPUT.relative_to(ROOT)} ({size} B of HTML) and {PREVIEW.relative_to(ROOT)}')


if __name__ == '__main__':

    main()

